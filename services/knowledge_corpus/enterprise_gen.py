def load_profile() -> str:
    parts = []
    for txt in sorted(PROFILE_DIR.glob("*.txt")):
        parts.append(f"【{txt.stem}】\n" + txt.read_text(encoding="utf-8", errors="ignore")[:1200])
    return "\n\n".join(parts)


async def generate() -> None:
    from services.llm_factory import get_llm_gateway

    gw = get_llm_gateway()
    profile = load_profile()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    done = 0
    for name, kind, brief in DOC_PLAN:
        txt_path = OUT_DIR / f"{name}.txt"
        if txt_path.exists():
            done += 1
            continue
        user = (
            f"企业画像（示例口径）：\n{profile}\n\n"
            f"文档类型：{kind}\n生成要求：{brief}\n"
            "开头顶部注明一行：（AI 生成演示语料，数据为示例口径）"
        )
        try:
            text = await gw.chat(
                [
                    {"role": "system", "content": SYSTEM},
                    {"role": "user", "content": user},
                ],
                temperature=0.4,
                max_tokens=4096,
            )
        except Exception as exc:  # noqa: BLE001
            print(f"[fail] {name}: {exc}")
            await asyncio.sleep(5)
            continue
        txt_path.write_text(text, encoding="utf-8")
        (OUT_DIR / f"{name}.meta.json").write_text(
            json.dumps(
                {
                    "title": name,
                    "doc_kind": kind,
                    "corpus_tag": "AI 生成演示语料（调研增强，投产时由用户替换真实资料）",
                    "subject": "广州市科旭电子有限公司（示例口径）",
                    "generated_at": time.strftime("%Y-%m-%d %H:%M:%S"),
                    "chars": len(text),
                },
                ensure_ascii=False,
                indent=2,
            ),
            encoding="utf-8",
        )
        done += 1
        print(f"[{done}/{len(DOC_PLAN)}] {name} ({len(text)} chars)")
    print(f"generation done: {done}/{len(DOC_PLAN)}")


if __name__ == "__main__":
    asyncio.run(generate())
